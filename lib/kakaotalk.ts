// 카카오톡 아이디.
//
// 로그인이 주는 `kakao_id`(회원번호)와 다른 값이다. 그건 앱마다 다르게 발급되는
// 내부 식별자라 카카오톡 친구찾기에 넣을 수 없다. 연결은 운영자가 카톡에서 두 사람을
// 직접 찾아 단톡방을 만드는 방식이므로(PRODUCT 45), 찾을 수 있는 값이 따로 필요하다.
//
// 선택이다. 카카오톡 아이디는 기본으로 있는 값이 아니라 설정에서 직접 만들어야 하고,
// 가입 화면에서 그걸 요구하면 거기서 이탈한다. 비어 있으면 닉네임으로 찾는다.

/** 영문·숫자와 마침표, 밑줄, 하이픈만. 한글이나 공백이 들어오면 오타로 본다 */
const SHAPE = /^[a-zA-Z0-9._-]{2,50}$/;

/**
 * 폼 입력을 저장할 값으로 바꾼다.
 * 붙여넣기로 들어오는 흔한 군더더기(@, 앞뒤 공백)를 털고, 형식이 아니면 null이다.
 * 빈 값과 잘못된 값을 똑같이 null로 떨어뜨린다 - 선택 항목이라 입력을 막지 않는다.
 */
export function parseKakaotalkId(raw: FormDataEntryValue | null): string | null {
  const v = String(raw ?? '')
    .trim()
    .replace(/^@/, '');
  return SHAPE.test(v) ? v : null;
}
